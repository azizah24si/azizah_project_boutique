// Fungsi helper untuk filter dan analisis data
export const getCustomerById = (id) => {
  return customersData.find(customer => customer.id === id);
};

export const getActiveCustomers = () => {
  return customersData.filter(customer => customer.statusMember === "Aktif");
};

export const getCustomersByLevel = (level) => {
  return customersData.filter(customer => customer.levelMember === level);
};

export const getCustomersByCity = (kota) => {
  return customersData.filter(customer => customer.kota === kota);
};

export const getCustomersWithActivePromo = () => {
  return customersData.filter(customer => customer.statusPromo === "Aktif");
};

export const getTotalTransactionValue = () => {
  return customersData.reduce((total, customer) => total + customer.totalTransaksi, 0);
};

export const getCustomersBySource = (sumber) => {
  return customersData.filter(customer => customer.sumberCustomer === sumber);
};

export default customersData;
